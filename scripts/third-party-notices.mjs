// Generates THIRD-PARTY-NOTICES.md — license notices for every package whose
// code is compiled INTO the shipped browser bundle (`vite build` inlines its
// imports; the server build uses --packages=external, so server deps stay in
// node_modules where npm delivers their own license files).
//
// Why this exists (K.8 caveat, found 2026-07-27): the browser-side libraries
// are classified as devDependencies — `npx license-checker --production`
// structurally cannot see them, but they ARE distributed (published to npm in
// dist/ and served to every viewport). MIT/BSD require the license text to
// accompany copies; MPL-2.0 (dompurify, inside mermaid's prebuilt bundle) has
// file-level notice obligations. This file is the compliance vehicle.
//
// Run after any web-side dependency change:  node scripts/third-party-notices.mjs
// ROOTS = the external imports of web/src (grep for `from "` / dynamic
// imports there) — update the list when a new browser dependency lands.

import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOTS = [
  "react",
  "react-dom",
  "react-markdown",
  "remark-gfm",
  "rehype-highlight",
  "qrcode-generator",
  "mermaid", // inlined verbatim as mermaid.min.js (?raw import) — its own deps (d3, dompurify, …) are embedded in that prebuilt file
];

const seen = new Map(); // name -> {version, license, licenseText}
const missing = [];
const queue = [...ROOTS];

while (queue.length) {
  const name = queue.shift();
  if (seen.has(name)) continue;
  const dir = join(repo, "node_modules", name);
  if (!existsSync(join(dir, "package.json"))) {
    missing.push(name);
    continue;
  }
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  let licenseText = null;
  for (const f of readdirSync(dir)) {
    if (/^(licen[cs]e|copying)(\.|$)/i.test(f)) {
      licenseText = readFileSync(join(dir, f), "utf8").trim();
      break;
    }
  }
  let license = typeof pkg.license === "string" ? pkg.license : JSON.stringify(pkg.license);
  if (!license && licenseText)
    license = "no SPDX field — see license text"; // e.g. khroma: MIT license file, no package.json field
  seen.set(name, { version: pkg.version, license, licenseText });
  for (const dep of Object.keys(pkg.dependencies ?? {})) queue.push(dep);
}

const names = [...seen.keys()].sort();
let out = `# Third-party notices

Mirafold's own code is MIT (see LICENSE). The shipped browser bundle
(\`dist/\`, built by Vite and served to every viewport) additionally compiles
in the open-source packages below. Their licenses and copyright notices are
reproduced here in full, as those licenses require. Server-side dependencies
are not bundled (installed separately by npm, each carrying its own license
file in node_modules) and the agent engines carry their own licenses — see
README §12.

Where a package is dual-licensed with an OR expression, Mirafold elects the
permissive option: **dompurify** (compiled inside mermaid's prebuilt bundle)
is offered under \`MPL-2.0 OR Apache-2.0\`, and Mirafold takes it under
**Apache-2.0**.

Generated by \`scripts/third-party-notices.mjs\` — regenerate after any
web-side dependency change.

## Package summary

| package | version | license |
| --- | --- | --- |
`;
for (const n of names) {
  const p = seen.get(n);
  out += `| ${n} | ${p.version} | ${p.license} |\n`;
}
out += `\n## License texts\n`;
for (const n of names) {
  const p = seen.get(n);
  out += `\n---\n\n### ${n}@${p.version} (${p.license})\n\n`;
  out += p.licenseText
    ? "```\n" + p.licenseText + "\n```\n"
    : `_No license file ships in the package; license declared as ${p.license} in its package.json._\n`;
}

writeFileSync(join(repo, "THIRD-PARTY-NOTICES.md"), out);
console.log(`wrote THIRD-PARTY-NOTICES.md: ${names.length} packages`);
if (missing.length) console.warn("NOT FOUND in node_modules (fix before shipping):", missing.join(", "));
const flagged = names.filter((n) => !/^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|CC0-1\.0|Unlicense)$/.test(seen.get(n).license));
if (flagged.length) console.log("non-trivial licenses (review these):", flagged.map((n) => `${n}=${seen.get(n).license}`).join(", "));
